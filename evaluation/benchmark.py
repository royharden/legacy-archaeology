def seal_commitment(public_manifest: dict, sealed_assets_sha256: str) -> dict:
    """Pure commitment construction; caller owns external immutable persistence."""
    if len(sealed_assets_sha256) != 64 or any(c not in '0123456789abcdef' for c in sealed_assets_sha256):
        raise ValueError('sealed assets digest required')
    payload = {'schema_version': 1, 'stage': 'T0', 'public_manifest': public_manifest,
               'sealed_assets_sha256': sealed_assets_sha256}
    return {**payload, 'commitment_sha256': digest(payload)}


def freeze_configuration(pins: dict, commitment_sha256: str) -> dict:
    if set(pins) != set(FREEZE_KEYS):
        raise ValueError('freeze requires exact release/config/prompt/policy/model/price/caps/scorer/floor/ranker pins')
    if any(not isinstance(value, str) or len(value) != 64 or any(c not in '0123456789abcdef' for c in value)
           for value in [commitment_sha256, *pins.values()]):
        raise ValueError('freeze requires SHA256 pins')
    payload = {'schema_version': 1, 'stage': 'T2', 'commitment_sha256': commitment_sha256, 'pins': dict(pins)}
    return {**payload, 'freeze_sha256': digest(payload)}


def hidden_run_eligibility(freeze: dict | None, custody: dict | None) -> dict:
    """Legacy structural diagnostic only, never actual runner authorization.

    JSON flags/hash strings do not establish OS isolation. Use the signed captured
    observation + append-only edition registry API for an execution decision.
    """
    missing = []
    if not freeze:
        missing.append('missing_T2_freeze')
    elif freeze.get('freeze_sha256') != digest({key: value for key, value in freeze.items() if key != 'freeze_sha256'}):
        missing.append('freeze_hash_mismatch')
    elif freeze.get('stage') != 'T2' or set(freeze.get('pins', {})) != set(FREEZE_KEYS) or not freeze.get('commitment_sha256'):
        missing.append('incomplete_T2_freeze')
    required = ('separate_os_identity', 'absolute_read_denied', 'relative_read_denied',
                'list_denied', 'no_inherited_handles', 'no_oracle_broker',
                'inference_distribution_excludes_evaluator', 'prompt_allowlist_verified', 'independent_review_verified')
    for key in required:
        if not custody or custody.get(key) is not True:
            missing.append(key)
    if not custody or not custody.get('evidence_sha256'):
        missing.append('custody_evidence_pin')
    return {'eligible': False, 'structurally_complete': not missing,
            'eligibility_level': 'unverified_structural_only',
            'missing': missing + ['verified_observation_receipts_and_edition_registry_required'],
            'benchmark_status': 'not_run', 'product_acceptance': 'pending'}


@dataclass
class SimulatedSME:
    """Evaluator-controlled offered-ID answers only; no free text/offset broker.

    accepted_choice_ids is a sealed evaluator policy, never inference-visible.
    Question contents are limited to shared Question wire fields by caller schema.
    """
    accepted_choice_ids: dict[str, str]
    submitted: int = 0
    cap: int = 12

    def answer(self, question: dict) -> dict:
        if self.submitted >= self.cap:
            raise ValueError('question budget exhausted')
        self.submitted += 1
        options = question.get('options', [])
        offered = {option['id'] if isinstance(option, dict) else option for option in options}
        if 'unknown' not in offered:
            raise ValueError('Question must offer unknown')
        desired = self.accepted_choice_ids.get(question['id'])
        selected = desired if desired in offered else 'unknown'
        return {'question_id': question['id'], 'option_id': selected,
                'actor': 'agent_provisional', 'reason': 'sealed simulated SME offered-option policy',
                'submitted_questions': self.submitted}


