def validate_arm_observation(method: str, observation: dict) -> list[str]:
    """Keep failed attempts and extra information visible in later reports."""
    arm = ARMS[method]
    violations = []
    attempts = observation.get('request_attempts')
    if type(attempts) is not int or attempts < 0 or attempts > arm['max_requests']:
        violations.append('request_budget')
    if method == 'B1' and attempts != 1:
        violations.append('single_pass_requires_exactly_one_attempt')
    if not arm['answers'] and observation.get('questions_answered', 0):
        violations.append('answers_not_permitted')
    if observation.get('questions_asked', 0) > 12:
        violations.append('question_budget')
    if observation.get('sample_records', 0) > 64:
        violations.append('sample_budget')
    if observation.get('input_tokens_max', 0) > 8000 or observation.get('output_tokens_max', 0) > 2000:
        violations.append('token_budget')
    return violations
